-- 1. Sequences for Auto-generating Primary Keys
CREATE SEQUENCE SEQ_DEPARTMENTS START WITH 10 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_DOCTORS START WITH 100 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_PATIENTS START WITH 1000 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_USERS START WITH 500 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_DOCTOR_AVAILABILITY START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_APPOINTMENTS START WITH 5000 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_PRESCRIPTIONS START WITH 7000 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_PRESCRIPTION_ITEMS START WITH 8000 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_BILLS START WITH 9000 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_BILL_ITEMS START WITH 10000 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_PAYMENTS START WITH 12000 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_AUDIT_LOG START WITH 1 INCREMENT BY 1 NOCACHE;

-- 2. DEPARTMENTS Table
CREATE TABLE DEPARTMENTS (
    DEPARTMENT_ID   NUMBER PRIMARY KEY,
    DEPARTMENT_NAME VARCHAR2(100) NOT NULL UNIQUE,
    DESCRIPTION     VARCHAR2(500),
    ACTIVE          NUMBER(1) DEFAULT 1 NOT NULL,
    CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT CHK_DEPT_ACTIVE CHECK (ACTIVE IN (0, 1))
);

-- Trigger for DEPARTMENTS Primary Key
CREATE OR REPLACE TRIGGER TRG_DEPARTMENTS_BI
BEFORE INSERT ON DEPARTMENTS
FOR EACH ROW
WHEN (NEW.DEPARTMENT_ID IS NULL)
BEGIN
    SELECT SEQ_DEPARTMENTS.NEXTVAL INTO :NEW.DEPARTMENT_ID FROM DUAL;
END;
/

