SET PAGESIZE 100;
SET LINESIZE 200;

-- 1. Table Record Counts
PROMPT === Table Record Counts ===
SELECT 'DEPARTMENTS' AS TABLE_NAME, COUNT(*) AS RECORD_COUNT FROM DEPARTMENTS
UNION ALL
SELECT 'DOCTORS', COUNT(*) FROM DOCTORS
UNION ALL
SELECT 'DOCTOR_AVAILABILITY', COUNT(*) FROM DOCTOR_AVAILABILITY
UNION ALL
SELECT 'PATIENTS', COUNT(*) FROM PATIENTS
UNION ALL
SELECT 'USERS', COUNT(*) FROM USERS
UNION ALL
SELECT 'APPOINTMENTS', COUNT(*) FROM APPOINTMENTS
UNION ALL
SELECT 'PRESCRIPTIONS', COUNT(*) FROM PRESCRIPTIONS
UNION ALL
SELECT 'PRESCRIPTION_ITEMS', COUNT(*) FROM PRESCRIPTION_ITEMS
UNION ALL
SELECT 'BILLS', COUNT(*) FROM BILLS
UNION ALL
SELECT 'BILL_ITEMS', COUNT(*) FROM BILL_ITEMS
UNION ALL
SELECT 'PAYMENTS', COUNT(*) FROM PAYMENTS
UNION ALL
SELECT 'AUDIT_LOG', COUNT(*) FROM AUDIT_LOG;

-- 2. Doctor and Department Join Check
PROMPT === Doctors by Department ===
SELECT d.DOCTOR_ID, d.DOCTOR_NAME, dep.DEPARTMENT_NAME, d.SPECIALIZATION, d.CONSULTATION_FEE, d.ROOM_NO
FROM DOCTORS d
JOIN DEPARTMENTS dep ON d.DEPARTMENT_ID = dep.DEPARTMENT_ID
ORDER BY dep.DEPARTMENT_NAME, d.DOCTOR_NAME;

-- 3. Appointment Summary Check
PROMPT === Appointments with Doctor and Patient Info ===
SELECT a.APPOINTMENT_ID, p.PATIENT_NAME, d.DOCTOR_NAME, dep.DEPARTMENT_NAME,
       TO_CHAR(a.APPOINTMENT_DATE, 'YYYY-MM-DD') AS APPT_DATE, a.APPOINTMENT_TIME, a.STATUS
FROM APPOINTMENTS a
JOIN PATIENTS p ON a.PATIENT_ID = p.PATIENT_ID
JOIN DOCTORS d ON a.DOCTOR_ID = d.DOCTOR_ID
JOIN DEPARTMENTS dep ON d.DEPARTMENT_ID = dep.DEPARTMENT_ID
ORDER BY a.APPOINTMENT_DATE DESC, a.APPOINTMENT_TIME;

-- 4. Billing and Revenue Verification
PROMPT === Revenue & Outstanding Balance Summary ===
SELECT 
    COUNT(b.BILL_ID) AS TOTAL_BILLS,
    NVL(SUM(b.TOTAL_AMOUNT), 0) AS TOTAL_BILLED,
    NVL(SUM(b.PAID_AMOUNT), 0) AS TOTAL_COLLECTED,
    NVL(SUM(b.BALANCE_AMOUNT), 0) AS TOTAL_OUTSTANDING
FROM BILLS b;

-- 5. Prescriptions with Items Check
PROMPT === Prescriptions and Prescribed Medicines ===
SELECT pr.PRESCRIPTION_ID, p.PATIENT_NAME, d.DOCTOR_NAME, pr.DIAGNOSIS,
       pi.MEDICINE_NAME, pi.DOSAGE, pi.DURATION
FROM PRESCRIPTIONS pr
JOIN PATIENTS p ON pr.PATIENT_ID = p.PATIENT_ID
JOIN DOCTORS d ON pr.DOCTOR_ID = d.DOCTOR_ID
LEFT JOIN PRESCRIPTION_ITEMS pi ON pr.PRESCRIPTION_ID = pi.PRESCRIPTION_ID
ORDER BY pr.PRESCRIPTION_ID, pi.ITEM_ID;

-- 6. User Accounts and Linked Roles Check
PROMPT === Active Users and Linked Roles ===
SELECT u.USER_ID, u.USERNAME, u.FULL_NAME, u.ROLE,
       NVL(TO_CHAR(u.PATIENT_ID), 'N/A') AS PATIENT_ID,
       NVL(TO_CHAR(u.DOCTOR_ID), 'N/A') AS DOCTOR_ID,
       u.ACTIVE
FROM USERS u
ORDER BY u.ROLE, u.USERNAME;
