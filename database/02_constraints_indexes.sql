-- 1. Foreign Key Constraints

-- DOCTORS -> DEPARTMENTS
ALTER TABLE DOCTORS
ADD CONSTRAINT FK_DOC_DEPT FOREIGN KEY (DEPARTMENT_ID)
REFERENCES DEPARTMENTS (DEPARTMENT_ID);

-- USERS -> PATIENTS & DOCTORS
ALTER TABLE USERS
ADD CONSTRAINT FK_USER_PATIENT FOREIGN KEY (PATIENT_ID)
REFERENCES PATIENTS (PATIENT_ID) ON DELETE CASCADE;

ALTER TABLE USERS
ADD CONSTRAINT FK_USER_DOCTOR FOREIGN KEY (DOCTOR_ID)
REFERENCES DOCTORS (DOCTOR_ID) ON DELETE CASCADE;

-- DOCTOR_AVAILABILITY -> DOCTORS
ALTER TABLE DOCTOR_AVAILABILITY
ADD CONSTRAINT FK_AVAIL_DOC FOREIGN KEY (DOCTOR_ID)
REFERENCES DOCTORS (DOCTOR_ID) ON DELETE CASCADE;

-- APPOINTMENTS -> PATIENTS & DOCTORS
ALTER TABLE APPOINTMENTS
ADD CONSTRAINT FK_APPT_PATIENT FOREIGN KEY (PATIENT_ID)
REFERENCES PATIENTS (PATIENT_ID);

ALTER TABLE APPOINTMENTS
ADD CONSTRAINT FK_APPT_DOCTOR FOREIGN KEY (DOCTOR_ID)
REFERENCES DOCTORS (DOCTOR_ID);

-- PRESCRIPTIONS -> APPOINTMENTS, DOCTORS, PATIENTS
ALTER TABLE PRESCRIPTIONS
ADD CONSTRAINT FK_PRESC_APPT FOREIGN KEY (APPOINTMENT_ID)
REFERENCES APPOINTMENTS (APPOINTMENT_ID);

ALTER TABLE PRESCRIPTIONS
ADD CONSTRAINT FK_PRESC_DOC FOREIGN KEY (DOCTOR_ID)
REFERENCES DOCTORS (DOCTOR_ID);

ALTER TABLE PRESCRIPTIONS
ADD CONSTRAINT FK_PRESC_PAT FOREIGN KEY (PATIENT_ID)
REFERENCES PATIENTS (PATIENT_ID);

-- PRESCRIPTION_ITEMS -> PRESCRIPTIONS
ALTER TABLE PRESCRIPTION_ITEMS
ADD CONSTRAINT FK_ITEM_PRESC FOREIGN KEY (PRESCRIPTION_ID)
REFERENCES PRESCRIPTIONS (PRESCRIPTION_ID) ON DELETE CASCADE;

-- BILLS -> PATIENTS & APPOINTMENTS
ALTER TABLE BILLS
ADD CONSTRAINT FK_BILL_PATIENT FOREIGN KEY (PATIENT_ID)
REFERENCES PATIENTS (PATIENT_ID);

ALTER TABLE BILLS
ADD CONSTRAINT FK_BILL_APPT FOREIGN KEY (APPOINTMENT_ID)
REFERENCES APPOINTMENTS (APPOINTMENT_ID);

-- BILL_ITEMS -> BILLS
ALTER TABLE BILL_ITEMS
ADD CONSTRAINT FK_ITEM_BILL FOREIGN KEY (BILL_ID)
REFERENCES BILLS (BILL_ID) ON DELETE CASCADE;

-- PAYMENTS -> BILLS
ALTER TABLE PAYMENTS
ADD CONSTRAINT FK_PAY_BILL FOREIGN KEY (BILL_ID)
REFERENCES BILLS (BILL_ID);

-- AUDIT_LOG -> USERS
ALTER TABLE AUDIT_LOG
ADD CONSTRAINT FK_AUDIT_USER FOREIGN KEY (USER_ID)
REFERENCES USERS (USER_ID);

-- 2. Performance Indexes for Frequent Searches & Filtering

-- (Note: USERS.USERNAME already has an automatic unique index from UNIQUE constraint)
CREATE INDEX IDX_USERS_ROLE ON USERS (ROLE);

CREATE INDEX IDX_PATIENTS_PHONE ON PATIENTS (PHONE);
CREATE INDEX IDX_PATIENTS_EMAIL ON PATIENTS (EMAIL);
CREATE INDEX IDX_PATIENTS_NAME ON PATIENTS (PATIENT_NAME);

CREATE INDEX IDX_DOCTORS_DEPT ON DOCTORS (DEPARTMENT_ID);
CREATE INDEX IDX_DOCTORS_SPEC ON DOCTORS (SPECIALIZATION);

CREATE INDEX IDX_AVAIL_DOC_DAY ON DOCTOR_AVAILABILITY (DOCTOR_ID, DAY_OF_WEEK);

CREATE INDEX IDX_APPT_PATIENT ON APPOINTMENTS (PATIENT_ID);
CREATE INDEX IDX_APPT_DOCTOR ON APPOINTMENTS (DOCTOR_ID);
CREATE INDEX IDX_APPT_DATE ON APPOINTMENTS (APPOINTMENT_DATE);
CREATE INDEX IDX_APPT_STATUS ON APPOINTMENTS (STATUS);
CREATE INDEX IDX_APPT_LOOKUP ON APPOINTMENTS (DOCTOR_ID, APPOINTMENT_DATE, APPOINTMENT_TIME, STATUS);

CREATE INDEX IDX_BILLS_PATIENT ON BILLS (PATIENT_ID);
CREATE INDEX IDX_BILLS_STATUS ON BILLS (STATUS);
CREATE INDEX IDX_PAYMENTS_BILL ON PAYMENTS (BILL_ID);
CREATE INDEX IDX_PAYMENTS_DATE ON PAYMENTS (PAYMENT_DATE);
CREATE INDEX IDX_AUDIT_ENTITY ON AUDIT_LOG (ENTITY_TYPE, ENTITY_ID);
